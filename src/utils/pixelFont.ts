export interface TextRenderOptions {
  size: 'small' | 'tall';
  spacing: number;
  intensity: Exclude<IntensityLevel, 0>;
  alignX?: 'left' | 'center' | 'right' | 'custom';
  alignY?: 'top' | 'center' | 'bottom' | 'custom';
  customCol?: number;
  customRow?: number;
}

export function renderTextToPixels(
  rawText: string,
  options: TextRenderOptions
): { pixels: PresetPixel[]; width: number; height: number; startCol: number; startRow: number } {
  const font = options.size === 'tall' ? FONT_7PX : FONT_5PX;
  const charHeight = options.size === 'tall' ? 7 : 5;
  const cleanText = rawText.toUpperCase().slice(0, 16);
  const spacing = Math.max(1, Math.min(3, options.spacing));

  const relativePixels: PresetPixel[] = [];
  let cursorX = 0;

  for (let i = 0; i < cleanText.length; i++) {
    const ch = cleanText[i];
    const glyph = font[ch] || font[' '];
    const glyphW = glyph[0]?.length ?? 3;

    for (let r = 0; r < glyph.length; r++) {
      const rowStr = glyph[r];
      for (let c = 0; c < rowStr.length; c++) {
        if (rowStr[c] === '#') {
          relativePixels.push({
            col: cursorX + c,
            row: r,
            level: options.intensity,
          });
        }
      }
    }
    cursorX += glyphW + (i < cleanText.length - 1 ? spacing : 0);
  }

  const width = Math.max(1, cursorX);
  const height = charHeight;

  let startCol = options.customCol ?? 2;
  if (options.alignX === 'left') startCol = 1;
  else if (options.alignX === 'center') startCol = Math.max(0, Math.floor((53 - width) / 2));
  else if (options.alignX === 'right') startCol = Math.max(0, 52 - width);

  let startRow = options.customRow ?? 0;
  if (options.alignY === 'top') startRow = 0;
  else if (options.alignY === 'center') startRow = Math.max(0, Math.floor((7 - height) / 2));
  else if (options.alignY === 'bottom') startRow = Math.max(0, 7 - height);

  const placedPixels = relativePixels
    .map((p) => ({
      col: p.col + startCol,
      row: p.row + startRow,
      level: p.level,
    }))
    .filter((p) => p.col >= 0 && p.col < 53 && p.row >= 0 && p.row < 7);

  return { pixels: placedPixels, width, height, startCol, startRow };
}
